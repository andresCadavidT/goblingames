#!/usr/bin/env bash
# Reproducible build of @newgoblin/bee-sdk (packages/bee-sdk) from the official Acki Nacki bee-engine
# sources: gosh-sh/bee-engine v6.0.0 + the audited patches in patches/bee-sdk/*.patch.
# Spec §4.2b; Windows requirements and quirks: docs/research/2026-10-31-bee-sdk-patch-design.md §F.
# See tools/bee-sdk/README.md.
#
# Usage: bash tools/bee-sdk/build.sh [--no-patches]
#
# Never touches the user's global git/cargo config: git settings are process-scoped
# (GIT_CONFIG_COUNT/KEY_n/VALUE_n), inherited by cargo's git-fetch-with-cli.
set -euo pipefail

UPSTREAM_REPO="https://github.com/gosh-sh/bee-engine"
UPSTREAM_TAG="v6.0.0"
UPSTREAM_COMMIT="015bc466613e7b7c41f272dc16ba0cacbf0e4d93"
PKG_NAME="@newgoblin/bee-sdk"
PKG_VERSION="6.0.0-ng.3"
# wasm-bindgen that produced the official @teamgosh/bee-sdk@6.0.0 (its .wasm "producers" section:
# wasm-bindgen 0.2.129, rustc 1.99.0). The glue JS is generated by this exact version, so pin it
# (with its lockstep js-sys/web-sys/futures/test releases) when generating Cargo.lock.
WASM_BINDGEN_VERSION="0.2.129"

usage() { echo "usage: bash tools/bee-sdk/build.sh [--no-patches]" >&2; }
die() { echo "build.sh: ERROR: $*" >&2; exit 1; }
step() { echo; echo "=== [$(date +%H:%M:%S)] $* ==="; }

NO_PATCHES=0
for arg in "$@"; do
  case "$arg" in
    --no-patches) NO_PATCHES=1 ;;
    -h|--help) usage; exit 0 ;;
    *) usage; exit 2 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
BUILD_DIR="$REPO_ROOT/.build"          # gitignored
SRC="$BUILD_DIR/bee-engine"            # fresh clone on every run
PATCH_DIR="$REPO_ROOT/patches/bee-sdk"
OUT="$REPO_ROOT/packages/bee-sdk"
# Cargo target dir lives OUTSIDE the clone so a fresh clone does not throw away the compiled deps.
export CARGO_TARGET_DIR="$BUILD_DIR/target"

# --- process-scoped git config (research §F.1) ---------------------------------------------------
# 0: gosh_tls_lib is declared as ssh://git@github.com/... (bee_wallet/Cargo.toml) but is readable over
#    anonymous HTTPS. 1: deep paths in the halo2/axiom forks. 2: Git for Windows ships
#    core.autocrlf=true system-wide; CRLF checkouts would change include_str!'d sources (and so the
#    .wasm) and break patches made against upstream's LF files.
export GIT_CONFIG_COUNT=3
export GIT_CONFIG_KEY_0="url.https://github.com/.insteadOf" GIT_CONFIG_VALUE_0="ssh://git@github.com/"
export GIT_CONFIG_KEY_1="core.longpaths"                     GIT_CONFIG_VALUE_1="true"
export GIT_CONFIG_KEY_2="core.autocrlf"                      GIT_CONFIG_VALUE_2="false"
export CARGO_NET_GIT_FETCH_WITH_CLI=true   # also set in upstream .cargo/config.toml
export GIT_TERMINAL_PROMPT=0               # never hang on a credential prompt

# --- toolchain ----------------------------------------------------------------------------------
step "toolchain"
for t in git cargo rustc rustup wasm-pack node; do
  command -v "$t" >/dev/null 2>&1 || die "missing tool: $t (see tools/bee-sdk/README.md)"
done
rustup target list --installed | tr -d '\r' | grep -qx wasm32-unknown-unknown \
  || die "missing rust target: rustup target add wasm32-unknown-unknown"
RUSTC_V="$(rustc -V | tr -d '\r')"
WASM_PACK_V="$(wasm-pack -V | tr -d '\r')"
echo "$RUSTC_V"; echo "$WASM_PACK_V"; cargo -V; node -v

# --- 1. clean clone, pinned and verified -------------------------------------------------------
step "clone $UPSTREAM_REPO @ $UPSTREAM_TAG"
mkdir -p "$BUILD_DIR"
rm -rf "$SRC"
git clone --quiet --depth 1 --branch "$UPSTREAM_TAG" -c advice.detachedHead=false \
  "$UPSTREAM_REPO.git" "$SRC"
ACTUAL="$(git -C "$SRC" rev-parse 'HEAD^{commit}')"
[ "$ACTUAL" = "$UPSTREAM_COMMIT" ] \
  || die "tag $UPSTREAM_TAG resolves to $ACTUAL, expected $UPSTREAM_COMMIT - refusing to build"
echo "commit $ACTUAL verified"

# --- 2. drop dodex-sdk (dev-dep only, pulls the huge halo2 graph; same as upstream CI) ----------
step "strip dodex-sdk from bee_wallet/Cargo.toml"
WALLET_TOML="$SRC/bee_wallet/Cargo.toml"
[ "$(grep -c '^dodex-sdk = ' "$WALLET_TOML" || true)" = 1 ] || die "expected exactly one dodex-sdk line in $WALLET_TOML"
sed -i '/^dodex-sdk = /d' "$WALLET_TOML"
! grep -q '^dodex-sdk = ' "$WALLET_TOML" || die "dodex-sdk still present"

# --- 3. patches ---------------------------------------------------------------------------------
PATCHES=()
if [ "$NO_PATCHES" = 0 ]; then
  step "apply patches/bee-sdk/*.patch"
  shopt -s nullglob
  PATCHES=("$PATCH_DIR"/*.patch)
  shopt -u nullglob
  [ "${#PATCHES[@]}" -gt 0 ] || die "no patches in $PATCH_DIR (use --no-patches for a plain upstream build)"
  for p in "${PATCHES[@]}"; do
    echo "--- $(basename "$p")"
    git -C "$SRC" apply --check "$p" || die "patch does not apply: $p"
    git -C "$SRC" apply "$p"
  done
else
  step "--no-patches: plain upstream build"
fi

# --- 4. Cargo.lock (upstream does not commit one) ---------------------------------------------
step "Cargo.lock"
if [ -f "$PATCH_DIR/Cargo.lock" ]; then
  [ -f "$PATCH_DIR/LOCK-INFO.json" ] || die "patches/bee-sdk/LOCK-INFO.json missing (provenance of Cargo.lock); delete Cargo.lock to regenerate both"
  cp "$PATCH_DIR/Cargo.lock" "$SRC/Cargo.lock"
  LOCK_MODE="reused"
  echo "using committed patches/bee-sdk/Cargo.lock"
else
  (cd "$SRC" && cargo generate-lockfile \
    && cargo update -p wasm-bindgen -p js-sys -p web-sys -p wasm-bindgen-futures -p wasm-bindgen-test \
         --precise "$WASM_BINDGEN_VERSION")
  mkdir -p "$PATCH_DIR"
  cp "$SRC/Cargo.lock" "$PATCH_DIR/Cargo.lock"
  # Provenance of the resolve (when, with what, unpinned git deps' SHAs); audited=false until reviewed.
  node "$SCRIPT_DIR/lock-info.mjs" write "$PATCH_DIR/Cargo.lock" "$PATCH_DIR/LOCK-INFO.json" \
    "$(cargo -V | tr -d '\r')" "$RUSTC_V" "$WASM_BINDGEN_VERSION"
  [ -f "$PATCH_DIR/LOCK-INFO.json" ] || die "lock-info.mjs did not write LOCK-INFO.json"
  LOCK_MODE="generated"
  echo "generated a fresh Cargo.lock -> patches/bee-sdk/Cargo.lock (commit it)"
fi
LOCKED_WB="$(grep -A1 '^name = "wasm-bindgen"$' "$SRC/Cargo.lock" | sed -n 's/^version = "\(.*\)"$/\1/p' | tr -d '\r')"
[ "$LOCKED_WB" = "$WASM_BINDGEN_VERSION" ] \
  || die "Cargo.lock has wasm-bindgen '$LOCKED_WB', expected $WASM_BINDGEN_VERSION (as upstream's npm build)"
echo "wasm-bindgen $LOCKED_WB (pinned)"

# --- 5. RUSTFLAGS: strip machine paths (research §F.2) ------------------------------------------
# rustc sees native Windows paths (C:\Users\...), so Git Bash's /c/Users/... prefixes would never
# match: remap the Windows spellings (both separators). rustc applies the LAST matching rule, so the
# generic prefixes go first. `--cfg tokio_unstable` mirrors upstream .cargo/config.toml
# [build].rustflags, which the upstream release build (plain `wasm-pack build`) inherits and which
# setting rustflags here would otherwise drop. CARGO_ENCODED_RUSTFLAGS (0x1f-separated) keeps paths
# with spaces intact.
winpath() { if command -v cygpath >/dev/null 2>&1; then cygpath -w "$1"; else printf '%s' "$1"; fi; }
FLAGS=(--cfg tokio_unstable)
remap() { # <posix path> <replacement>
  local w; w="$(winpath "$1")"
  FLAGS+=("--remap-path-prefix=$w=$2")
  [ "${w//\\//}" = "$w" ] || FLAGS+=("--remap-path-prefix=${w//\\//}=$2")
}
remap "$HOME" /home
remap "${RUSTUP_HOME:-$HOME/.rustup}" /rustup
remap "${CARGO_HOME:-$HOME/.cargo}" /cargo
remap "$REPO_ROOT" /repo
remap "$SRC" /build
unset RUSTFLAGS
CARGO_ENCODED_RUSTFLAGS="$(IFS=$'\x1f'; printf '%s' "${FLAGS[*]}")"
export CARGO_ENCODED_RUSTFLAGS
printf '  %s\n' "${FLAGS[@]}"

# --- 6. build -------------------------------------------------------------------------------------
step "wasm-pack build --target web --release (bee_sdk/)"
(cd "$SRC/bee_sdk" && rm -rf pkg && wasm-pack build --target web --release -- --locked)
PKG="$SRC/bee_sdk/pkg"
ARTIFACTS=(bee_sdk.js bee_sdk_bg.wasm bee_sdk.d.ts bee_sdk_bg.wasm.d.ts)
for f in "${ARTIFACTS[@]}"; do [ -f "$PKG/$f" ] || die "wasm-pack did not produce $f"; done

# --- 7. assemble in a staging dir (packages/bee-sdk is only replaced once everything passed) ------
STAGE="$BUILD_DIR/pkg-staging"
step "assemble $PKG_NAME in .build/pkg-staging"
rm -rf "$STAGE"
mkdir -p "$STAGE"
for f in "${ARTIFACTS[@]}"; do cp "$PKG/$f" "$STAGE/$f"; done
HAS_SNIPPETS=0
if [ -d "$PKG/snippets" ]; then cp -r "$PKG/snippets" "$STAGE/snippets"; HAS_SNIPPETS=1; fi
cp "$SRC/LICENSE.md" "$SRC/NOTICE.md" "$STAGE/"
{
  printf '%s\n\n' "> Este paquete es una compilación de NewGoblin de @teamgosh/bee-sdk 6.0.0 desde el código fuente oficial; ver BUILD-INFO.json."
  cat "$SRC/bee_sdk/README.md"
} > "$STAGE/README.md"

# Native paths, one per line: Git Bash converts a POSIX path in an env var for node.exe only when the
# whole value is one path, so from the second patch on Node would get /c/Users/... (= C:\c\Users\...).
PATCH_LIST=""
for p in "${PATCHES[@]+"${PATCHES[@]}"}"; do PATCH_LIST+="$(winpath "$p")"$'\n'; done
NG_OUT="$STAGE" NG_NAME="$PKG_NAME" NG_VERSION="$PKG_VERSION" \
NG_UPSTREAM_REPO="$UPSTREAM_REPO" NG_UPSTREAM_TAG="$UPSTREAM_TAG" NG_UPSTREAM_COMMIT="$ACTUAL" \
NG_PATCHES="$PATCH_LIST" NG_LOCK="$SRC/Cargo.lock" NG_LOCK_MODE="$LOCK_MODE" \
NG_LOCK_INFO="$PATCH_DIR/LOCK-INFO.json" \
NG_RUSTC="$RUSTC_V" NG_WASM_PACK="$WASM_PACK_V" NG_SNIPPETS="$HAS_SNIPPETS" \
  node "$SCRIPT_DIR/write-package.mjs"

# --- 8. leak gate over every staged file ----------------------------------------------------------
# Fail closed: besides the exit code, require the CLI's exact summary line, so a scan that did not
# actually run (or scanned fewer files) cannot pass.
step "scan staged files for machine paths"
mapfile -t STAGED < <(find "$STAGE" -type f | sort)
SCAN_OUT="$(node "$SCRIPT_DIR/scan-paths-cli.mjs" "${STAGED[@]}")" || { echo "$SCAN_OUT"; die "machine paths leaked into the build output"; }
echo "$SCAN_OUT"
[ "$(printf '%s\n' "$SCAN_OUT" | tail -n 1 | tr -d '\r')" = "scan-paths: OK ${#STAGED[@]} files" ] \
  || die "leak gate did not report 'scan-paths: OK ${#STAGED[@]} files'"

# --- 9. swap into the workspace package -------------------------------------------------------
step "publish -> packages/bee-sdk"
rm -rf "$OUT"
mv "$STAGE" "$OUT"

step "done"
cat "$OUT/BUILD-INFO.json"
