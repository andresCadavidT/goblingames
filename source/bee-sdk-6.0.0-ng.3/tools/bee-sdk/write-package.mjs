#!/usr/bin/env node
// Called by tools/bee-sdk/build.sh after the artifacts are copied: writes packages/bee-sdk/package.json
// and BUILD-INFO.json (provenance: upstream commit, patches + sha256, artifact hashes, toolchain).
// Inputs come from NG_* environment variables (see build.sh).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';
import { readLockInfo } from './lock-info.mjs';

const env = (k) => {
  const v = process.env[k];
  if (v === undefined) throw new Error(`write-package: missing ${k}`);
  return v;
};
const sha256 = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');
const writeJson = (path, obj) => writeFileSync(path, JSON.stringify(obj, null, 2) + '\n');

const out = env('NG_OUT');
const artifacts = ['bee_sdk.js', 'bee_sdk_bg.wasm', 'bee_sdk.d.ts', 'bee_sdk_bg.wasm.d.ts'];
const hasSnippets = env('NG_SNIPPETS') === '1';
const lock = readFileSync(env('NG_LOCK'), 'utf8');
const lockVersion = (name) =>
  lock.match(new RegExp(`\\[\\[package\\]\\]\\r?\\nname = "${name}"\\r?\\nversion = "([^"]+)"`))?.[1] ?? null;

const pkg = {
  name: env('NG_NAME'),
  version: env('NG_VERSION'),
  private: true,
  description:
    'Self-built gosh-sh/bee-engine bee_sdk (wasm-pack --target web). GENERATED by tools/bee-sdk/build.sh, do not edit; provenance in BUILD-INFO.json.',
  type: 'module',
  // bee-engine NOTICE.md: GNU AGPL version 3 (no "or later").
  license: 'AGPL-3.0-only',
  repository: { type: 'git', url: env('NG_UPSTREAM_REPO') },
  // AGPL "Corresponding Source" of this build = upstream at upstreamCommit + these NewGoblin paths.
  newgoblinSource: {
    upstream: `${env('NG_UPSTREAM_REPO')} @ ${env('NG_UPSTREAM_COMMIT')}`,
    patches: 'patches/bee-sdk/ (*.patch, Cargo.lock, LOCK-INFO.json)',
    buildScripts: 'tools/bee-sdk/',
    docs: 'tools/bee-sdk/README.md#licencia-y-código-fuente-correspondiente',
  },
  main: 'bee_sdk.js',
  module: 'bee_sdk.js',
  types: 'bee_sdk.d.ts',
  exports: {
    '.': { types: './bee_sdk.d.ts', default: './bee_sdk.js' },
    './bee_sdk_bg.wasm': './bee_sdk_bg.wasm',
    './BUILD-INFO.json': './BUILD-INFO.json',
    './package.json': './package.json',
  },
  files: [...artifacts, ...(hasSnippets ? ['snippets'] : []), 'BUILD-INFO.json', 'LICENSE.md', 'NOTICE.md', 'README.md'],
  // Same as the upstream npm package (@teamgosh/bee-sdk 6.0.0).
  sideEffects: ['./snippets/*'],
};

writeJson(join(out, 'package.json'), pkg);

const lockInfo = readLockInfo(env('NG_LOCK_INFO'), readFileSync(env('NG_LOCK')));
const hashed = readdirSync(out, { recursive: true, withFileTypes: true })
  .filter((d) => d.isFile())
  .map((d) => relative(out, join(d.parentPath, d.name)).replaceAll('\\', '/'))
  .filter((f) => f !== 'BUILD-INFO.json')
  .sort();

const patches = env('NG_PATCHES')
  .split('\n')
  .filter(Boolean)
  .map((p) => ({ name: basename(p), sha256: sha256(p) }));

const info = {
  upstreamRepo: env('NG_UPSTREAM_REPO'),
  upstreamTag: env('NG_UPSTREAM_TAG'),
  upstreamCommit: env('NG_UPSTREAM_COMMIT'),
  patches,
  removedDependencies: ['bee_wallet/Cargo.toml: dodex-sdk (dev-dependency, as upstream CI)'],
  cargoLock: {
    path: 'patches/bee-sdk/Cargo.lock',
    sha256: sha256(env('NG_LOCK')),
    mode: env('NG_LOCK_MODE'),
    unpinnedGitDeps: lockInfo.gitDeps.unpinned.map((d) => `${d.url} (${d.pin === 'branch' ? `branch ${d.ref}` : 'default branch'}) @ ${d.sha}`),
  },
  lockResolvedAt: lockInfo.resolvedAt,
  lockAudited: lockInfo.audited,
  note:
    `${lockInfo.note} Built with ${env('NG_RUSTC')} (upstream's npm 6.0.0 build used rustc 1.99.0): ` +
    'the artifact is NOT byte-identical to @teamgosh/bee-sdk 6.0.0 (public API identical, see tools/bee-sdk/README.md).',
  wasmSha256: sha256(join(out, 'bee_sdk_bg.wasm')),
  // Every file of the package except BUILD-INFO.json itself (checked by tools/bee-sdk-build-info.test.mjs).
  files: Object.fromEntries(hashed.map((f) => [f, sha256(join(out, f))])),
  rustc: env('NG_RUSTC'),
  wasmPack: env('NG_WASM_PACK'),
  wasmBindgen: lockVersion('wasm-bindgen'),
  target: 'wasm32-unknown-unknown',
  wasmPackArgs: 'build --target web --release -- --locked',
  builtAt: process.env.SOURCE_DATE_EPOCH
    ? new Date(Number(process.env.SOURCE_DATE_EPOCH) * 1000).toISOString()
    : new Date().toISOString(),
};

writeJson(join(out, 'BUILD-INFO.json'), info);
console.log(`wrote ${pkg.name}@${pkg.version} (wasm sha256 ${info.wasmSha256})`);
